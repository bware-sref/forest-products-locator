<?php

namespace Database\Factories;

use App\Enums\PublicationStatus;
use App\Models\Mill;
use App\Models\MillEdit;
use App\Models\State;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * A public submission awaiting review.
 *
 * Default: proposed changes to an existing mill (the mill-edit form). Use newBusiness() for an Add Your Business
 * submission, which has no mill yet.
 *
 * proposed_changes mirrors what MillController stores: ['diff' => [field => [from, to]], 'changes' => [field => to]].
 * Pass the changed fields with withChanges(); diff is built from the mill's current values.
 *
 * Review/approve/reject hashes are generated by MillEdit::booted().
 *
 * @extends Factory<MillEdit>
 */
class MillEditFactory extends Factory
{
    public function definition(): array
    {
        return [
            'mill_id' => Mill::factory(),
            'submitter_email' => fake()->safeEmail(),
            'submitter_ip' => fake()->ipv4(),
            'status' => PublicationStatus::Pending,
            'proposed_changes' => fn (array $attributes) => self::proposedChanges(
                self::millFrom($attributes),
                ['mill_name' => fake()->company()],
            ),
        ];
    }

    /**
     * Propose these field values for the mill (form field names, e.g. 'mill_types' => [ids]).
     */
    public function withChanges(array $changes): static
    {
        /**
         * A closure *value*, so it runs while the attributes are resolved (after mill_id has become a real mill),
         * not up front like a state closure.
         */
        return $this->state([
            'proposed_changes' => fn (array $attributes) => self::proposedChanges(self::millFrom($attributes), $changes),
        ]);
    }

    /**
     * An Add Your Business submission: no mill yet, every form field proposed.
     * Pass overrides for any of the proposed fields.
     */
    public function newBusiness(array $changes = []): static
    {
        return $this->state(function () use ($changes) {
            $stateId = $changes['state_id'] ?? State::factory()->create()->id;

            return [
                'mill_id' => null,
                'proposed_changes' => ['diff' => [], 'changes' => [
                    'mill_name' => fake()->company().' Lumber',
                    'physical_address' => fake()->streetAddress(),
                    'physical_city' => fake()->city(),
                    'state_id' => $stateId,
                    'physical_zip' => fake()->postcode(),
                    'mailing_address' => null,
                    'mailing_city' => null,
                    'mailing_state_id' => null,
                    'mailing_zip' => null,
                    'telephone' => fake()->numerify('706-555-####'),
                    'email' => fake()->companyEmail(),
                    'mill_types' => [],
                    'wood_species' => [],
                    ...$changes,
                ]],
            ];
        });
    }

    public function approved(): static
    {
        return $this->state(['status' => PublicationStatus::Approved, 'reviewed_at' => now()]);
    }

    public function rejected(): static
    {
        return $this->state(['status' => PublicationStatus::Rejected, 'reviewed_at' => now()]);
    }

    /**
     * The mill being edited. ->for($mill) may still supply mill_id as a closure that returns the id.
     */
    private static function millFrom(array $attributes): ?Mill
    {
        $mill = $attributes['mill_id'] ?? null;

        if ($mill instanceof \Closure) {
            $mill = $mill();
        }

        return match (true) {
            $mill instanceof Mill => $mill,
            null === $mill => null,
            default => Mill::withoutGlobalScopes()->find($mill),
        };
    }

    /**
     * Built the way Mill::diff() builds it: the relationship fields are always present in changes.
     */
    private static function proposedChanges(?Mill $mill, array $changes): array
    {
        $changes = [
            'mill_types' => $mill?->millTypes()->pluck('mill_types.id')->all() ?? [],
            'wood_species' => $mill?->woodSpecies()->pluck('wood_species.id')->all() ?? [],
            ...$changes,
        ];

        $diff = collect($changes)
            ->except(Mill::N_TO_N)
            ->map(fn ($to, $field) => ['from' => $mill?->{$field} ?? '', 'to' => $to ?? ''])
            ->all();

        return ['diff' => $diff, 'changes' => $changes];
    }
}
